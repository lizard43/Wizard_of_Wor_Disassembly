    LD A,$0C
    CALL Print_String_Color
    LD HL,UI_Row2_Marker
    LD DE,$0A00
    LD B,$01
    LD A,$08
    CALL Print_String_Color
    LD HL,UI_Row3_Text
    LD DE,$0F02
    LD B,$27
    LD A,$0C
    CALL Print_String_Color
    LD HL,UI_Row3_Marker
    LD DE,$0F00
    LD B,$01
    LD A,$08
    CALL Print_String_Color
    LD HL,UI_Row4_Text
    LD DE,$1402
